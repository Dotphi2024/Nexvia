        foreach ($catalog as $item) {
            $catData = $item['category'];
            $category = Category::updateOrCreate(
                ['slug' => $catData['slug']],
                [
                    'name' => $catData['name'],
                    'type' => $catData['type'],
                    'referral_category_code' => $catData['referral_category_code'],
                    'referral_eligible' => $catData['referral_eligible'] ?? true,
                    'commission_percentage' => $catData['commission_percentage'] ?? 10.00,
                    'icon' => $catData['icon'],
                    'description' => $catData['description'],
                    'image' => $catData['image'],
                    'sort_order' => $catData['sort_order'] ?? 0,
                    'is_active' => $catData['is_active'] ?? true,
                ]
            );
            $totalCategories++;

            foreach ($item['products'] as $prodData) {
                $slug = Str::slug($prodData['name']);
                $mrp = (float) $prodData['mrp'];
                $bookingPct = 20;
                $bookingAmount = round($mrp * ($bookingPct / 100), 2);
                $balanceAmount = round($mrp - $bookingAmount, 2);
                $referralValue = round($mrp * 0.10, 2);

                Product::updateOrCreate(
                    ['model_code' => $prodData['model_code']],
                    [
                        'category_id' => $category->id,
                        'name' => $prodData['name'],
                        'slug' => $slug,
                        'sku' => $prodData['sku'],
                        'mrp' => $mrp,
                        'booking_percentage' => $bookingPct,
                        'booking_amount' => $bookingAmount,
                        'balance_amount' => $balanceAmount,
                        'eligible_referral_value' => $referralValue,
                        'referral_eligible' => true,
                        'self_dealer_eligible' => true,
                        'stock' => 50,
                        'overview' => $prodData['overview'],
                        'offer_text' => $prodData['offer_text'] ?? null,
                        'main_image' => $prodData['main_image'],
                        'gallery' => $prodData['gallery'] ?? [$prodData['main_image']],
                        'key_features' => $prodData['key_features'] ?? [],
                        'specs' => $prodData['specs'] ?? [],
                        'warranty_info' => $prodData['warranty_info'] ?? '1 Year Brand Warranty',
                        'installation_info' => $prodData['installation_info'] ?? 'Free Standard Installation Available',
                        'delivery_info' => $prodData['delivery_info'] ?? 'Dispatched within 2-4 business days',
                        'is_featured' => $prodData['is_featured'] ?? false,
                        'status' => 'active',
                    ]
                );
                $totalProducts++;
            }
        }

        $this->command->info("Seeded {$totalCategories} categories and {$totalProducts} products successfully.");
    }
